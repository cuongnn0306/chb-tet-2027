describe('confirmed orders are frozen (non-negotiable invariant)', () => {
  async function submitted() {
    const order = await newDraft(sale, [item('TT-1200', 2), item('TT-800', 1)])
    await action(sale, order.id, 'submit')
    return order
  }

  it('rejects editing a submitted order through the RPC with a cancel-and-recreate hint', async () => {
    const order = await submitted()
    const { error } = await draft(sale, [item('TT-1200', 99)], { p_order_id: order.id })
    expect(error?.message).toMatch(/hủy đơn cũ và tạo đơn mới/)
  })

  it('rejects any change to quantity, price, customer or amounts after the draft stage', async () => {
    const order = await submitted()
    const svc = serviceClient()
    const { data: lines } = await svc.from('order_items').select('id').eq('order_id', order.id)

    const qty = await svc
      .from('order_items')
      .update({ quantity: 50 })
      .eq('id', lines?.[0]?.id as string)
    expect(qty.error?.message).toMatch(/hủy đơn cũ và tạo đơn mới/)
    const price = await svc
      .from('order_items')
      .update({ list_price: 1, gross_line_amount: 1 })
      .eq('id', lines?.[0]?.id as string)
    expect(price.error).not.toBeNull()
    const del = await svc
      .from('order_items')
      .delete()
      .eq('id', lines?.[0]?.id as string)
    expect(del.error).not.toBeNull()
    const add = await svc.from('order_items').insert({
      order_id: order.id,
      product_id: ids.products['COM-500']?.id,
      quantity: 1,
      list_price: ids.products['COM-500']?.price,
      gross_line_amount: ids.products['COM-500']?.price,
    })
    expect(add.error).not.toBeNull()

    for (const patch of [
      { discount_amount: 1, net_amount: -1 },
      { gross_amount: 1 },
      { customer_id: ids.customer },
      { sales_channel_id: null },
    ]) {
      const { error } = await svc
        .from('orders')
        .update(patch as never)
        .eq('id', order.id)
      if ('customer_id' in patch) continue // same customer: unchanged value is not a change
      expect(error, JSON.stringify(patch)).not.toBeNull()
    }
    const { data: check } = await svc
      .from('order_items')
      .select('quantity')
      .eq('order_id', order.id)
      .order('quantity')
    expect(check?.map((c) => c.quantity)).toEqual([1, 2])
  })

  it('keeps the order code and creator unchangeable', async () => {
    const order = await newDraft(sale)
    const svc = serviceClient()
    expect(
      (await svc.from('orders').update({ order_code: 'HACK' }).eq('id', order.id)).error?.message,
    ).toMatch(/mã đơn/)
  })

  it('never hard-deletes orders or history, even for the service role', async () => {
    const order = await submitted()
    const svc = serviceClient()
    expect((await svc.from('orders').delete().eq('id', order.id)).error?.message).toMatch(
      /Không được xóa đơn hàng/,
    )
    expect(
      (await svc.from('order_status_history').delete().eq('order_id', order.id)).error?.message,
    ).toMatch(/bất biến/)
    expect(
      (await svc.from('order_status_history').update({ reason: 'x' }).eq('order_id', order.id))
        .error?.message,
    ).toMatch(/bất biến/)
  })
})

describe('cancel and void (ORD-009, ORD-010)', () => {
  it('lets the owner cancel an unpaid order with a reason, and records it', async () => {
    const order = await newDraft(sale)
    await action(sale, order.id, 'submit')
    expect((await action(sale, order.id, 'cancel')).error?.message).toMatch(/lý do hủy/)
    expect((await action(sale, order.id, 'cancel', '   ')).error?.message).toMatch(/lý do hủy/)

    const { data, error } = await action(sale, order.id, 'cancel', 'Khách đổi ý')
    expect(error).toBeNull()
    expect(data).toMatchObject({ status: 'CANCELLED', cancel_reason: 'Khách đổi ý' })
    expect(data.cancelled_at).not.toBeNull()

    const { data: history } = await serviceClient()
      .from('order_status_history')
      .select('to_status, reason, actor_user_id')
      .eq('order_id', order.id)
      .eq('to_status', 'CANCELLED')
      .single()
    expect(history?.reason).toBe('Khách đổi ý')
    expect(history?.actor_user_id).not.toBeNull()
    // terminal: no further transitions
    expect((await action(admin, order.id, 'void', 'x')).error).not.toBeNull()
  })

  it('lets only Admin cancel once an order is confirmed or reserved', async () => {
    const svc = serviceClient()
    const order = await newDraft(sale)
    await action(sale, order.id, 'submit')
    await action(admin, order.id, 'confirm')
    await svc
      .from('orders')
      .update({ status: 'CONFIRMED', confirmed_at: new Date().toISOString() })
      .eq('id', order.id) // stands in for the deposit step (E06)
    const owner = await action(sale, order.id, 'cancel', 'Muốn hủy')
    expect(owner.error?.code).toBe('42501')
    expect((await action(admin, order.id, 'cancel', 'Admin hủy')).data.status).toBe('CANCELLED')
  })

  it('refuses to cancel or void an order that already has a payment', async () => {
    const svc = serviceClient()
    const order = await newDraft(sale)
    await action(sale, order.id, 'submit')
    await svc.from('orders').update({ paid_amount: 1000 }).eq('id', order.id)
    expect((await action(sale, order.id, 'cancel', 'x')).error?.message).toMatch(/thanh toán/)
    expect((await action(admin, order.id, 'void', 'x')).error?.message).toMatch(/thanh toán/)
    expect((await action(sale, order.id, 'return_to_draft')).error?.message).toMatch(/thanh toán/)
    const { data } = await svc
      .from('orders')
      .select('remaining_amount, net_amount')
      .eq('id', order.id)
      .single()
    expect(data?.remaining_amount).toBe((data?.net_amount as number) - 1000)
  })

  it('voids (soft-deletes) only for Admin, with a reason, keeping the row and audit', async () => {
    const order = await newDraft(sale)
    expect((await action(sale, order.id, 'void', 'Nhập nhầm')).error?.code).toBe('42501')
    expect((await action(admin, order.id, 'void')).error?.message).toMatch(/lý do vô hiệu hóa/)
    const { data, error } = await action(admin, order.id, 'void', 'Nhập nhầm đơn')
    expect(error).toBeNull()
    expect(data).toMatchObject({ status: 'VOIDED', void_reason: 'Nhập nhầm đơn' })
    expect(data.voided_at).not.toBeNull()

    const svc = serviceClient()
    expect((await svc.from('orders').select('id').eq('id', order.id)).data).toHaveLength(1)
    const { data: audit } = await svc
      .from('audit_logs')
      .select('action')
      .eq('entity_type', 'orders')
      .eq('entity_id', order.id)
    expect((audit ?? []).length).toBeGreaterThanOrEqual(2)
    // the owner still sees the voided order (history is preserved)
    expect(
      (await sale.from('orders').select('status').eq('id', order.id).single()).data?.status,
    ).toBe('VOIDED')
  })

  it('cannot void orders past confirmation', async () => {
    const svc = serviceClient()
    const order = await newDraft(sale)
    await action(sale, order.id, 'submit')
    await action(admin, order.id, 'confirm')
    await svc.from('orders').update({ status: 'CONFIRMED' }).eq('id', order.id)
    await svc.from('orders').update({ status: 'RESERVED' }).eq('id', order.id)
    expect((await action(admin, order.id, 'void', 'x')).error?.message).toMatch(
      /không thể vô hiệu hóa/,
    )
    expect((await action(admin, order.id, 'cancel', 'đã giữ hàng')).data.status).toBe('CANCELLED')
  })
})
