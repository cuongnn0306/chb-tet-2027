async function clientFor(email: string): Promise<AppSupabaseClient> {
  const { url, anonKey } = getLocalConfig()
  const client = createClient<Database>(url, anonKey, {
    auth: { persistSession: false, autoRefreshToken: false },
  })
  const { error } = await client.auth.signInWithPassword({ email, password: TEST_PASSWORD })
  if (error) throw error
  return client
}

// Loosely typed RPC call: tests pass nulls and extra keys on purpose.
const rpc = (client: AppSupabaseClient, fn: string, args: Record<string, unknown>) =>
  (
    client as unknown as {
      rpc: (
        f: string,
        a: unknown,
      ) => PromiseLike<{ data: Record<string, any>; error: Record<string, any> | null }>
    }
  ).rpc(fn, args)

interface Ids {
  customer: string
  products: Record<string, { id: string; price: number }>
}

let ids: Ids
let sale: AppSupabaseClient
let store: AppSupabaseClient
let admin: AppSupabaseClient
let warehouse: AppSupabaseClient

beforeAll(async () => {
  ;[sale, store, admin, warehouse] = await Promise.all([
    clientFor(TEST_USERS.sale),
    clientFor(TEST_USERS.store),
    clientFor(TEST_USERS.admin),
    clientFor(TEST_USERS.warehouse),
  ])
  const svc = serviceClient()
  const { data: customer } = await svc
    .from('customers')
    .select('id')
    .eq('phone_normalized', '0900000003')
    .single()
  const { data: products } = await svc.from('products').select('id, sku, list_price')
  ids = {
    customer: customer?.id as string,
    products: Object.fromEntries(
      (products ?? []).map((p) => [p.sku, { id: p.id, price: p.list_price }]),
    ),
  }
})

const item = (sku: string, quantity: number) => ({ product_id: ids.products[sku]?.id, quantity })

async function draft(
  client: AppSupabaseClient,
  items: unknown[],
  extra: Record<string, unknown> = {},
) {
  return rpc(client, 'save_draft_order', {
    p_order_id: null,
    p_customer_id: ids.customer,
    p_items: items,
    p_discount_amount: 0,
    ...extra,
  })
}

async function newDraft(client = sale, items: unknown[] = [item('TT-1200', 2)]) {
  const { data, error } = await draft(client, items)
  expect(error).toBeNull()
  return data as { id: string; order_code: string; status: string; net_amount: number }
}

async function action(client: AppSupabaseClient, id: string, act: string, reason?: string) {
  return rpc(client, 'transition_order', {
    p_order_id: id,
    p_action: act,
    p_reason: reason ?? null,
  })
}

