-- ---------------------------------------------------------------------------
-- Code boundary: lpad(x, 4) would turn 10000 into 'TR-1000' (a collision). Sequences are not transactional, so this
-- only ever moves the sequence FORWARD (never rewinds below an issued value); it runs last, and later suites only
-- need codes of four or more digits.
-- ---------------------------------------------------------------------------
select setval('private.transfer_code_seq', 9998)
where (select last_value from private.transfer_code_seq) < 9998;
select ok((select last_value from private.transfer_code_seq) = 9998, 'fixture: the sequence sits just below the four-digit boundary');

