select
  (select count(*) from public.inventory_movements) as movements,
  (select coalesce(sum(available_qty), 0) from public.inventory_balances) as available,
  (select coalesce(sum(reserved_qty), 0) from public.inventory_balances) as reserved,
  (select coalesce(sum(in_transfer_qty), 0) from public.inventory_balances) as in_transfer,
  (select count(*) from public.inventory_reservations) as reservations,
  (select count(*) from public.orders) as orders,
  (select count(*) from public.payments) as payments;
